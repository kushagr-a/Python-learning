# this is the example of immutable data types in python
# immutable data types are those data types whose value cannot be changed after they are created.

sugar_amount = 2
print(f"initial amount of sugar: {sugar_amount} teaspoons.")

sugar_amount = 12
print(f"second amount of sugar: {sugar_amount} teaspoons.")

# created new refrence to the same object
print(f"Id of 2: {id(2)}")
print(f"Id of 12: {id(12)}")
